    def validar_peso(self):
        try:
            pesoMin_num = float(self.line_nuevo_pesoMin.text().replace(",","."))
            self.pesoMin_num = pesoMin_num
            pesoMax_num = float(self.line_nuevo_pesoMax.text().replace(",","."))
            self.pesoMax_num = pesoMax_num
            self.cod_producto = self.obj.comboCodigo.currentText()
            #print(f" Producto: {self.cod_producto}. Peso maximo: {pesoMax_num}. Peso minimo: {pesoMin_num}")
            if pesoMin_num != 0 and pesoMax_num != 0 and self.line_nuevo_pesoMax.text() != ""  and (pesoMax_num > pesoMin_num):
                #print(f"Guardando producto. Peso min: {pesoMin_num}. Peso max: {pesoMax_num}. Codigo: {self.cod_producto}")
                try:
                    self.obj.objmgr.updatePesoMinBobina(self.cod_producto,pesoMin_num)
                    self.obj.objmgr.updatePesoMaxBobina(self.cod_producto,pesoMax_num)
                    #print("Exito")
                    MensajeOK = Dialog_msj("minimo_valido",self)
                    MensajeOK.setWindowModality(Qt.ApplicationModal)
                    MensajeOK.exec_()
                except Exception as e:
                    print(e)
            else:
                mensajeError = Dialog_msj("max_menor_que_min",self)
                mensajeError.setWindowModality(Qt.ApplicationModal)
                mensajeError.exec_()
        except Exception as e:
            print(e)
            mensajeError = Dialog_msj("campos_faltantes",self)
            mensajeError.setWindowModality(Qt.ApplicationModal)
            mensajeError.exec_()

    



