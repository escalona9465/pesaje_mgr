from PySide6.QtWidgets import (QLabel,QLineEdit,QComboBox,QVBoxLayout,QHBoxLayout,QDialog,QPushButton)
from PySide6.QtGui import QIcon,QCursor,QRegularExpressionValidator,QPixmap
from os.path import abspath
from PySide6.QtCore import Qt
from components.styles.popUp import STYLES_POPUP

class Mensajes(QDialog):
    def __init__(self, accion, padre=None):
        super(Mensajes, self).__init__()
        self.mensaje = QLabel()
        self.botonOK = QPushButton("OK")
        self.setStyleSheet(STYLES_POPUP)
        if accion == "producto_actualizado":
            self.setFixedSize(350,180)
            self.botonOK.setMaximumWidth(160)
            self.botonOK.clicked.connect(self.close)
            self.botonOK.setCursor(QCursor(Qt.PointingHandCursor))
            self.setWindowTitle("Producto actualizado")
            self.setWindowIcon(QIcon(abspath("components/sources/ok.png")))
            self.marco_iconoerror = QLabel()
            self.icono = QPixmap("components/sources/ok.png")
            self.marco_iconoerror.setPixmap(self.icono.scaled(40,40))
            self.marco_iconoerror.setFixedSize(40,40)
            self.mensaje.setText("El producto fue\nactualizado\nsatisfactoriamente.")
            self.mensaje.setAlignment(Qt.AlignCenter)
            self.centralLayout = QVBoxLayout()
            self.layout_mensajes = QHBoxLayout()
            self.layoutbotones = QHBoxLayout()
            self.layout_mensajes.addWidget(self.marco_iconoerror)
            self.layout_mensajes.addWidget(self.mensaje)
            self.layoutbotones.addWidget(self.botonOK)
            self.centralLayout.addLayout(self.layout_mensajes)
            self.centralLayout.addLayout(self.layoutbotones)
            self.setLayout(self.centralLayout)
        elif accion == "producto_eliminado":
            self.setFixedSize(350,180)
            self.botonOK.setMaximumWidth(160)
            self.botonOK.clicked.connect(self.close)
            self.botonOK.setCursor(QCursor(Qt.PointingHandCursor))
            self.setWindowTitle("Producto eliminado")
            self.setWindowIcon(QIcon(abspath("components/sources/ok.png")))
            self.marco_iconoerror = QLabel()
            self.icono = QPixmap("components/sources/ok.png")
            self.marco_iconoerror.setPixmap(self.icono.scaled(40,40))
            self.marco_iconoerror.setFixedSize(40,40)
            self.mensaje.setText("El producto fue\neliminado\nsatisfactoriamente.")
            self.mensaje.setAlignment(Qt.AlignCenter)
            self.centralLayout = QVBoxLayout()
            self.layout_mensajes = QHBoxLayout()
            self.layoutbotones = QHBoxLayout()
            self.layout_mensajes.addWidget(self.marco_iconoerror)
            self.layout_mensajes.addWidget(self.mensaje)
            self.layoutbotones.addWidget(self.botonOK)
            self.centralLayout.addLayout(self.layout_mensajes)
            self.centralLayout.addLayout(self.layoutbotones)
            self.setLayout(self.centralLayout)