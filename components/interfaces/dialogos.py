class DialogVerificacionImpresion(QDialog):
    def __init__(self, obj, accion):
        super(DialogVerificacionImpresion,self).__init__()
        self.accion = accion
        self.obj = obj
        self.validador = QDoubleValidator()
        self.setStyleSheet(STYLES_DIALOGOS)
        if self.accion == "agregar_pesoMin":
            self.setWindowTitle("Agregar peso mínimo")
            self.setWindowIcon(getAicon("danger"))
            self.setFixedSize(400,270)
            self.titulo = QLabel("El producto actual no posee un peso\n mínimo por bobina registrado.\nPor favor agréguelo a continuación.")
            self.titulo.setAlignment(Qt.AlignCenter)
            self.titulo.setObjectName("verificador")
            self.formlayout = QFormLayout()
            self.label_pesomin = QLabel("Min Kg Bobina")
            self.label_pesomin.setAlignment(Qt.AlignRight)
            self.label_pesomin.setMinimumWidth(200)
            self.label_pesomin.setObjectName("etiqueta")
            self.line_nuevo_pesoMin = QLineEdit()
            #self.line_nuevo_pesoMin.setValidator(self.validador)
            self.line_nuevo_pesoMin.setMaximumWidth(100)
            self.label_pesomax = QLabel("Max Kg Bobina")
            self.label_pesomax.setAlignment(Qt.AlignRight)
            self.label_pesomax.setMinimumWidth(200)
            self.label_pesomax.setObjectName("etiqueta")
            self.line_nuevo_pesoMax = QLineEdit()
            #self.line_nuevo_pesoMax.setValidator(self.validador)
            self.line_nuevo_pesoMax.setMaximumWidth(100)
